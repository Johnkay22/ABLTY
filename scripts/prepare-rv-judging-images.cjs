// Deterministic photographic derivatives, never generated replacement images.
// Run manually with Node and ffmpeg. Originals and historical paths stay intact.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'ablty-worker.js'), 'utf8');
const pool = vm.runInNewContext(source.match(/const RV_TARGET_POOL = \[[\s\S]*?\n\];/)[0] + '\nRV_TARGET_POOL');
const hashes = new Map();
const manifest = {};
fs.mkdirSync(path.join(root, 'targets/judging'), { recursive: true });
for (const target of pool) {
  const input = fs.readFileSync(path.join(root, target.src));
  const originalHash = createHash('sha256').update(input).digest('hex');
  const duplicate = hashes.get(originalHash);
  if (duplicate) { manifest[target.id] = { ...manifest[duplicate], canonical: duplicate }; continue; }
  hashes.set(originalHash, target.id);
  const src = 'targets/judging/' + path.basename(target.src);
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', path.join(root, target.src),
    '-vf', 'scale=768:768:flags=lanczos', '-map_metadata', '-1', '-frames:v', '1',
    '-q:v', '3', '-threads', '1', path.join(root, src)]);
  const bytes = fs.readFileSync(path.join(root, src));
  manifest[target.id] = { src, sha256: createHash('sha256').update(bytes).digest('hex'), canonical: target.id };
}
fs.writeFileSync(path.join(root, 'rv-judging-images.js'),
  '// Generated by scripts/prepare-rv-judging-images.cjs. No user data.\nexport const RV_JUDGING_IMAGES = '
  + JSON.stringify(manifest, null, 2) + ';\n');
console.log('Prepared ' + hashes.size + ' distinct 768px judging photos.');
